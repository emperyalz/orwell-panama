const adminMaps: Record<SiteLanguage, Record<string, string>> = { es: {}, en: {}, pt: {} };
for (const [en, es, pt] of rows) {
  if (en !== es) { adminMaps.es[en] = es; adminMaps.en[es] = en; }
  if (en !== pt) adminMaps.pt[en] = pt;
  if (es !== pt) adminMaps.pt[es] = pt;
}

export function translateAdminText(raw: string, lang: SiteLanguage): string {
  const clean = raw.trim();
  if (!clean) return raw;
  const dictionary = adminMaps[lang];
  let translated = dictionary[clean];
  if (!translated) {
    const prefix = Object.keys(dictionary).find((source) => source.endsWith('(') && clean.startsWith(source));
    if (prefix) translated = dictionary[prefix] + clean.slice(prefix.length);
  }
  if (!translated) {
    translated = clean;
    for (const source of Object.keys(dictionary).sort((a, b) => b.length - a.length)) {
      if (source.length < 5) continue;
      const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      translated = translated.replace(new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, 'gu'), dictionary[source]);
    }
  }
  return translated === clean ? raw : raw.replace(clean, translated);
}
